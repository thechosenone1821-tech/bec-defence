#!/usr/bin/env python3
"""Phase 9 — generate the one EVALS.md from the one results file.

This document and the MessageGuard compatibility pointer are generated. Never
hand-edit either file: ``make eval`` or ``python -m evals.run_evals`` regenerates
them and ``--check`` proves they have not drifted from ``evals/results.json``.
"""
from __future__ import annotations

import json
import pathlib
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT = ROOT / "EVALS.md"
POINTER_OUT = ROOT / "raksha" / "MESSAGEGUARD_EVALS.md"
RESULTS_PATH = ROOT / "evals" / "results.json"


def num(value: Any) -> str:
    return str(value)


def pct(value: Any) -> str:
    return f"{float(value) * 100:.1f}%"


def yes(value: Any) -> str:
    return "yes" if bool(value) else "no"


def render(results: dict[str, Any]) -> str:
    sections = results["sections"]
    citizen = sections["citizen"]
    mg = sections["messageguard"]
    organs = sections["organs"]
    gov = sections["governance"]
    replay = sections["replay"]
    lines: list[str] = []
    add = lines.append
    add("# RAKSHA — Unified Evaluation Results")
    add("")
    add("_Generated by `evals/gen_evals_md.py` from `evals/results.json`. "
        "Do not hand-edit. Regenerate and drift-check with `make eval`._")
    add("")
    add("Every number below carries a condition: fixture / synthetic / sandbox / "
        "hand-authored / real-world UNMEASURED. Real-world accuracy, latency, "
        "uptime, recall and false-positive rate remain UNMEASURED. No AI model, "
        "Commander endpoint, frozen VoiceGuard/MAYA eval, live executor or "
        "network service is used by this runner.")
    add("")
    add(f"Contract: `{results['contract']}`. Capabilities measured: "
        f"{num(results['capability_count'])}. Real-world claims: "
        f"`{results['measurement_policy']['real_world']}`.")
    add("")
    add("## Citizen — fixture / sandbox")
    add("")
    add(f"Condition: `{citizen['condition']}`. Source: `{citizen['source']}`. "
        f"Status: `{citizen['status']}`.")
    add("")
    add("| measurement | value |")
    add("|---|---:|")
    add(f"| health status | {num(citizen['health_status_code'])} |")
    add(f"| features status | {num(citizen['features_status_code'])} |")
    add(f"| manifest status | {num(citizen['manifest_status_code'])} |")
    add(f"| root redirect status | {num(citizen['root_redirect_status_code'])} |")
    add(f"| feature flags | {num(citizen['feature_flag_count'])} |")
    add(f"| app routes | {num(citizen['app_route_count'])} |")
    add(f"| no AI models | {yes(citizen['no_ai_models'])} |")
    add(f"| VoiceGuard integrated | {yes(citizen['voiceguard_integrated'])} |")
    add("")
    add("## MessageGuard — hand-authored / in-distribution")
    add("")
    add(f"Condition: `{mg['condition']}`. Source corpus: "
        f"`raksha-code/citizen/fixtures/messageguard/`. Scorer: "
        f"`{mg['detector_interface']}`. Status: `{mg['status']}`.")
    add("")
    add("| measurement | value |")
    add("|---|---:|")
    add(f"| hand-authored fixtures | {num(mg['corpus']['fixture_total'])} |")
    add(f"| scam fixtures | {num(mg['corpus']['scam_total'])} |")
    add(f"| benign fixtures | {num(mg['corpus']['benign_total'])} |")
    add(f"| true positives | {num(mg['overall']['tp_moderate'])} |")
    add(f"| true negatives | {num(mg['overall']['tn_moderate'])} |")
    add(f"| false positives | {num(mg['overall']['fp_moderate'])} |")
    add(f"| false negatives | {num(mg['overall']['fn_moderate'])} |")
    add(f"| accuracy | {pct(mg['overall']['accuracy_moderate'])} |")
    add(f"| precision | {pct(mg['overall']['precision_moderate'])} |")
    add(f"| detection | {pct(mg['overall']['recall_moderate'])} |")
    add(f"| false-positive rate | {pct(mg['overall']['fpr_moderate'])} |")
    add("")
    add("| language | scam caught | scam total | detection | high-score caught | high-score rate | critical | false positives | benign total | false-positive rate |")
    add("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for lang in ("en", "hi", "te", "hinglish"):
        row = mg["languages"][lang]
        add(f"| {lang} | {num(row['scam_caught_moderate'])} | {num(row['scam_total'])} | "
            f"{pct(row['detection_rate_moderate'])} | {num(row['scam_caught_high'])} | "
            f"{pct(row['detection_rate_high'])} | {num(row['critical_count'])} | "
            f"{num(row['fp_moderate'])} | {num(row['benign_total'])} | "
            f"{pct(row['fpr_moderate'])} |")
    add("")
    add("| family | labelled | hit | recall |")
    add("|---|---:|---:|---:|")
    for family, row in sorted(mg["family_recall"].items()):
        add(f"| {family} | {num(row['labelled'])} | {num(row['hit'])} | {pct(row['recall'])} |")
    add("")
    add("These figures support only the hand-authored / in-distribution claim. "
        "Real-world recall and FPR are UNMEASURED. Hinglish rows are part of the "
        "one corpus, not a second eval suite.")
    add("")
    add("## Organs — synthetic / sandbox")
    add("")
    add(f"Condition: `{organs['condition']}`. Source: `{organs['source']}`. "
        f"Status: `{organs['status']}`.")
    add("")
    add("| measurement | value |")
    add("|---|---:|")
    add(f"| organ count | {num(organs['organ_count'])} |")
    add(f"| registry count | {num(organs['registry_count'])} |")
    add(f"| fixture bundles | {num(organs['fixture_bundle_count'])} |")
    add(f"| firing fixtures producing findings | {num(organs['firing_findings'])} |")
    add(f"| silent fixtures with no detection | {num(organs['silent_no_detection'])} |")
    add(f"| missing-feature fixtures with no detection | {num(organs['missing_no_detection'])} |")
    add(f"| quarantine-before-detection cases | {num(organs['quarantine_before_detection'])} |")
    add(f"| unknown-organ quarantine cases | {num(organs['unknown_organ_quarantine'])} |")
    add(f"| VoiceGuard integrated | {yes(organs['voiceguard_integrated'])} |")
    add("")
    add("## Governance — sandbox")
    add("")
    add(f"Condition: `{gov['condition']}`. Source: `{gov['source']}`. "
        f"Status: `{gov['status']}`.")
    add("")
    add("| measurement | value |")
    add("|---|---:|")
    add(f"| proposals from the exhaustive planner | {num(gov['proposal_count'])} |")
    add(f"| allowed dry-run decisions | {num(gov['allowed_count'])} |")
    add(f"| first-class refusals | {num(gov['refused_count'])} |")
    add(f"| blast cap | {num(gov['blast_cap'])} |")
    add(f"| dry-run allowlisted actions | {num(gov['allowed_action_count'])} |")
    add(f"| real executor actions | {num(gov['executor_real_action_count'])} |")
    add(f"| crown-cut attempts rejected | {num(gov['crown_cut_attempts_rejected'])} |")
    add(f"| admin override | {gov['admin_override']} |")
    add("")
    add("## End-to-end replay — sandbox")
    add("")
    add(f"Condition: `{replay['condition']}`. Source: `{replay['source']}`. "
        f"Status: `{replay['status']}`.")
    add("")
    add("| measurement | value |")
    add("|---|---:|")
    add(f"| replay steps | {num(replay['campaign_step_count'])} |")
    add(f"| signed events | {num(replay['signed_event_count'])} |")
    add(f"| findings | {num(replay['finding_count'])} |")
    add(f"| verified no-detection events | {num(replay['no_detection_count'])} |")
    add(f"| quarantined events | {num(replay['quarantine_count'])} |")
    add(f"| decisions | {num(replay['decision_count'])} |")
    add(f"| dry-run executions | {num(replay['execution_count'])} |")
    add(f"| ledger height | {num(replay['ledger_height'])} |")
    add(f"| decisions snapshot count | {num(replay['decisions_snapshot_count'])} |")
    add(f"| quarantine snapshot count | {num(replay['quarantine_snapshot_count'])} |")
    add(f"| real executor actions | {num(replay['executor_real_action_count'])} |")
    add(f"| unsafe decisions | {num(replay['unsafe_decision_count'])} |")
    add(f"| admin override status | {num(replay['admin_override_status_code'])} |")
    add(f"| ledger chain valid | {yes(replay['ledger_valid'])} |")
    add(f"| no AI models | {yes(replay['no_ai_models'])} |")
    add(f"| Commander model invoked | {yes(replay['commander_model_invoked'])} |")
    add(f"| dry-run only | {yes(replay['dry_run'])} |")
    add(f"| VoiceGuard included | {yes(replay['voiceguard_included'])} |")
    add("")
    add("## Claims policy and VoiceGuard re-entry")
    add("")
    add("The one generated eval document is `EVALS.md`. The one claims ledger is "
        "`evals/claims_ledger.json`; its hand-authored documentation rows come from "
        "`evals/claims_sources.json`. No number may appear in a README, status "
        "page, changelog or pitch without a conditioned source row.")
    add("")
    add(f"VoiceGuard / MAYA evals are `{results['voiceguard']['contract_status']}`. "
        f"They are included in this runner: {yes(results['voiceguard']['included_in_runner'])}. "
        f"Re-entry is future Phase {results['voiceguard']['future_phase']}: "
        f"`{results['voiceguard']['reentry_gate']}`. Frozen assets stay unchanged.")
    add("")
    return "\n".join(lines)


def render_pointer(results: dict[str, Any]) -> str:
    mg = results["sections"]["messageguard"]
    return (
        "# MessageGuard results — generated compatibility pointer\n\n"
        "_Generated by `evals/gen_evals_md.py`; do not hand-edit. The one "
        "generated eval document is [`../EVALS.md`](../EVALS.md#messageguard)._\n\n"
        f"The canonical section covers {num(mg['corpus']['fixture_total'])} "
        "hand-authored / in-distribution fixtures in one corpus, including "
        "Hinglish rows. The one generated eval document carries every conditioned "
        "number and the claims ledger source. Real-world recall and FPR are "
        "UNMEASURED. This pointer exists only for historical links and tests; "
        "it is not a second eval suite.\n"
    )


def main(argv: list[str] | None = None) -> int:
    results = json.loads(RESULTS_PATH.read_text(encoding="utf-8"))
    OUT.write_text(render(results), encoding="utf-8")
    POINTER_OUT.write_text(render_pointer(results), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} and "
          f"{POINTER_OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

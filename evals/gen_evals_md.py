def render_pointer(results: dict[str, Any]) -> str:
    messageguard = results["sections"]["messageguard"]
    return (
        "# MessageGuard results — generated compatibility pointer\n\n"
        "_Generated by `evals/gen_evals_md.py`; do not hand-edit. The one "
        "generated eval document is [`../EVALS.md`](../EVALS.md#messageguard)._\n\n"
        f"Status: `{messageguard['status']}`. The canonical section covers the "
        "committed hand-authored / in-distribution corpus in one path, including "
        "Hinglish rows. The one generated eval document carries every conditioned "
        "number and the claims ledger source. Real-world recall and FPR are "
        "UNMEASURED. This pointer exists only for historical links and tests; "
        "it is not a second eval suite.\n"
    )


def main(argv: list[str] | None = None) -> int:
    results = json.loads(RESULTS_PATH.read_text(encoding="utf-8"))
    OUT.write_text(render(results), encoding="utf-8")
    POINTER_OUT.write_text(render_pointer(results), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} and "
          f"{POINTER_OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Phase 10 compatibility CLI for the one canonical MessageGuard measurement.

The computation lives in root ``evals/messageguard.py``. The committed
``results.json`` beside this file is generated by ``make eval``; ``--check``
proves it still matches the one scorer and one corpus. This is not a second
eval runner.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
OUT = pathlib.Path(__file__).with_name("results.json")
SOURCE = ROOT / "evals" / "messageguard.py"


def _module():
    spec = importlib.util.spec_from_file_location("raksha_unified_messageguard", SOURCE)
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load the canonical MessageGuard measurement")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


compute_results = _module().compute_results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    results = compute_results()
    if args.check:
        committed = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {}
        if committed != results:
            print("FAIL: MessageGuard results.json is stale; rerun make eval", file=sys.stderr)
            return 1
        print("OK: MessageGuard compatibility results match the canonical runner")
        return 0
    OUT.write_text(json.dumps(results, sort_keys=True, ensure_ascii=True, indent=2) + "\n",
                   encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

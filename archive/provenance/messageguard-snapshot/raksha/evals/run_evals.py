#!/usr/bin/env python3
"""MessageGuard evaluation runner.

Loads every fixture under fixtures/, scores it with the deterministic
scorer, and computes the numbers published in raksha/EVALS.md:

- scam detection rate per language at two thresholds (>=MODERATE, >=HIGH)
- per-family recall per language (which signal families actually fired)
- false-positive rate on the benign genuine-alert corpus, at both
  thresholds, with every FP case listed by kind
- overall accuracy at the >=MODERATE operating point

Writes evals/results.json (machine-readable) and prints a summary.
EVALS.md is generated by gen_evals_md.py from the same results.json so
the published numbers and the machine numbers cannot drift apart.

Usage:  cd raksha && python evals/run_evals.py
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from messageguard import analyze  # noqa: E402

FIXTURES = ROOT / "fixtures"
OUT = ROOT / "evals" / "results.json"

MODERATE, HIGH = 0.20, 0.70
FAMILIES = ["credential", "authority", "money_action", "prize", "urgency", "link_grab"]


def load_jsonl(path):
    with open(path, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def main():
    scam_by_lang = {"en": [], "hi": [], "te": []}
    benign_by_lang = {"en": [], "hi": [], "te": []}
    for path in sorted(FIXTURES.glob("*.jsonl")):
        for rec in load_jsonl(path):
            rec["_result"] = analyze(rec["text"])
            if rec["label"] == "scam":
                scam_by_lang[rec["lang"]].append(rec)
            else:
                benign_by_lang[rec["lang"]].append(rec)

    results = {
        "corpus": {
            "scam_total": sum(len(v) for v in scam_by_lang.values()),
            "benign_total": sum(len(v) for v in benign_by_lang.values()),
            "scam_by_lang": {k: len(v) for k, v in scam_by_lang.items()},
            "benign_by_lang": {k: len(v) for k, v in benign_by_lang.items()},
        },
        "languages": {},
        "family_recall": {},
        "benign_fp_cases": [],
    }

    for lang in ("en", "hi", "te"):
        scam = scam_by_lang[lang]
        benign = benign_by_lang[lang]

        caught_mod = sum(1 for r in scam if r["_result"]["score"] >= MODERATE)
        caught_high = sum(1 for r in scam if r["_result"]["score"] >= HIGH)
        crit = sum(1 for r in scam if r["_result"]["verdict"] == "CRITICAL")

        fp_mod = [r for r in benign if r["_result"]["score"] >= MODERATE]
        fp_high = [r for r in benign if r["_result"]["score"] >= HIGH]

        fam = {}
        for family in FAMILIES:
            labelled = [r for r in scam if family in r.get("families", [])]
            hit = [r for r in labelled if family in r["_result"]["families_fired"]]
            fam[family] = {
                "labelled": len(labelled),
                "hit": len(hit),
                "recall": round(len(hit) / len(labelled), 4) if labelled else None,
            }

        tn_mod = len(benign) - len(fp_mod)
        results["languages"][lang] = {
            "scam_caught_moderate": caught_mod,
            "scam_caught_high": caught_high,
            "scam_total": len(scam),
            "detection_rate_moderate": round(caught_mod / len(scam), 4),
            "detection_rate_high": round(caught_high / len(scam), 4),
            "critical_count": crit,
            "benign_total": len(benign),
            "fp_moderate": len(fp_mod),
            "fp_high": len(fp_high),
            "fpr_moderate": round(len(fp_mod) / len(benign), 4),
            "fpr_high": round(len(fp_high) / len(benign), 4),
            "tn_moderate": tn_mod,
            "family_recall": fam,
            "fp_cases": [
                {
                    "id": r["id"],
                    "kind": r.get("kind"),
                    "score": r["_result"]["score"],
                    "verdict": r["_result"]["verdict"],
                    "families_fired": r["_result"]["families_fired"],
                    "text": r["text"],
                }
                for r in fp_mod
            ],
        }
        results["benign_fp_cases"].extend(
            {"lang": lang, **c} for c in results["languages"][lang]["fp_cases"]
        )

    # overall accuracy at the >=MODERATE operating point
    total_scam = results["corpus"]["scam_total"]
    total_benign = results["corpus"]["benign_total"]
    tp = sum(results["languages"][l]["scam_caught_moderate"] for l in ("en", "hi", "te"))
    tn = sum(results["languages"][l]["tn_moderate"] for l in ("en", "hi", "te"))
    fp = sum(results["languages"][l]["fp_moderate"] for l in ("en", "hi", "te"))
    fn = total_scam - tp
    results["overall"] = {
        "tp_moderate": tp,
        "tn_moderate": tn,
        "fp_moderate": fp,
        "fn_moderate": fn,
        "accuracy_moderate": round((tp + tn) / (total_scam + total_benign), 4),
        "precision_moderate": round(tp / (tp + fp), 4) if (tp + fp) else None,
        "recall_moderate": round(tp / total_scam, 4),
        "fpr_moderate": round(fp / total_benign, 4),
    }

    OUT.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"scam={total_scam} benign={total_benign}")
    for lang in ("en", "hi", "te"):
        d = results["languages"][lang]
        print(
            f"{lang}: det@MOD={d['detection_rate_moderate']:.1%} det@HIGH={d['detection_rate_high']:.1%} "
            f"FPR@MOD={d['fpr_moderate']:.1%} FP={d['fp_moderate']}/{d['benign_total']}"
        )
    o = results["overall"]
    print(
        f"overall: accuracy={o['accuracy_moderate']:.1%} precision={o['precision_moderate']:.1%} "
        f"recall={o['recall_moderate']:.1%} FPR={o['fpr_moderate']:.1%}"
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
